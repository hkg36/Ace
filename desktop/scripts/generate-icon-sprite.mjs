export function generateIconSprite() {
  const colors = {
    'icon-error': 'var(--mw-status-danger)',
    'process-error': 'var(--mw-status-danger)',
    'status-running': 'var(--mw-action-primary)',
    'status-complete': 'var(--mw-status-success)',
    'loading-frame': 'var(--mw-action-primary)',
    'loading-stream': 'var(--mw-action-primary)',
  };
  const symbols = Object.entries(ICON_NAMES).map(([id, name]) => {
    const definition = icons[name];
    if (!definition) throw new Error(`Missing Font Awesome icon: ${name} (${id})`);
    const [width, height, , , data] = definition.icon;
    const size = /^(?:avatar-|team-|skill-badge|plugin-badge)/.test(id) ? 32 : 24;
    const scale = (size - 4) / Math.max(width, height);
    const x = (size - width * scale) / 2;
    const y = (size - height * scale) / 2;
    const paths = (Array.isArray(data) ? data : [data])
      .map((d) => `<path d="${d}"/>`).join('');
    const fill = colors[id] ?? 'var(--mw-symbol-line, currentColor)';
    return `    <symbol id="${id}" viewBox="0 0 ${size} ${size}"><g fill="${fill}" stroke="none" transform="translate(${x} ${y}) scale(${scale})">${paths}</g></symbol>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
  <!-- Generated by npm run icons:generate. Do not edit paths manually.
       Font Awesome Free by Fonticons, Inc. https://fontawesome.com/
       Icons licensed under CC BY 4.0: https://creativecommons.org/licenses/by/4.0/ -->
  <defs>
${symbols.join('\n')}
  </defs>
</svg>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../assets/crew-ui-symbols.svg', import.meta.url), generateIconSprite());
}
